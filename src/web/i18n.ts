export function isSupportedLocale(value: unknown): value is SupportedLocale {
  return value === "en" || value === "zh-TW";
}

export function getRequestLocale(request: Request): SupportedLocale {
  const queryLocale = Array.isArray(request.query.lang) ? request.query.lang[0] : request.query.lang;
  if (isSupportedLocale(queryLocale)) return queryLocale;

  const cookieLocale = parseCookie(request.headers.cookie ?? "").ui_lang;
  if (isSupportedLocale(cookieLocale)) return cookieLocale;

  const accepted = request.headers["accept-language"]?.toLowerCase() ?? "";
  return accepted.includes("zh-tw") || accepted.includes("zh-hant") ? "zh-TW" : "en";
}

export function createTranslator(locale: SupportedLocale): Translator {
  return (key, params = {}) => {
    const template = messages[locale][key] ?? messages.en[key] ?? key;
    return Object.entries(params).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template
    );
  };
}

export function buildLanguageSwitchUrl(request: Request, locale: SupportedLocale): string {
  const url = new URL(request.originalUrl || request.url, "http://photo-challenge.local");
  url.searchParams.set("lang", locale);
  return `${url.pathname}${url.search}${url.hash}`;
}

function parseCookie(header: string): Record<string, string> {
  return Object.fromEntries(
    header.split(";").map((part) => part.trim()).filter(Boolean).map((part) => {
      const separator = part.indexOf("=");
      const key = separator >= 0 ? part.slice(0, separator) : part;
      const value = separator >= 0 ? part.slice(separator + 1) : "";
      try {
        return [key, decodeURIComponent(value)];
      } catch {
        return [key, value];
      }
    })
  );
}
